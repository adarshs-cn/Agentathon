"""LiveMonitor: the supervisor watching a fixed pool of real borrowers, continuously, inside the compliance window.

  * It is a background worker that stays on while the server runs (not tied to anyone being logged in).
  * Inside the window (default: the policy's hard window, R007, 08:00-19:00) it appends events for the pool as they
    fall due and runs every event whose time has come. Outside the window it does nothing: events already waiting
    stay in the queue and are handled when the window opens.
  * The pool and each borrower's next-due time are stored in SQLite (`monitor_pool`), so a restart picks up where it
    stopped and never re-creates what already happened.

Events are generated by a simple schedule (a stand-in for a real event feed, which would call POST /api/events).
"""
from __future__ import annotations

import os
import random
import threading
import time
from datetime import datetime, timedelta

POOL_SIZE = 15
SCHEMA = """CREATE TABLE IF NOT EXISTS monitor_pool (
    customer_id TEXT PRIMARY KEY, account_id TEXT, dpd INTEGER, next_due REAL, events INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS monitor_meta (k TEXT PRIMARY KEY, v TEXT);"""


def parse_window(text: str | None, fallback: tuple[int, int]) -> tuple[int, int]:
    try:
        a, b = (text or "").split("-")
        f = lambda t: int(t[:2]) * 60 + int(t[3:5])  # noqa: E731
        return f(a), f(b)
    except Exception:  # noqa: BLE001
        return fallback


def hhmm(minutes: int) -> str:
    return f"{minutes // 60:02d}:{minutes % 60:02d}"


def setup_pool(sup, as_of: str, seed: int = 5, size: int = POOL_SIZE, stagger_s: int = 20) -> list[dict]:
    """Pick the pool once: 15 customers (reachable, not suppressed; a mix of due-soon and overdue) and the account
    each is watched on: events are published for that ACCOUNT."""
    from datetime import date
    from orchestrator.ui.scenario import CLEAN
    db = sup.ctx.db
    db.executescript(SCHEMA)
    have = db.query("SELECT * FROM monitor_pool ORDER BY rowid")
    if have:
        return [dict(r) for r in have]
    since = (date.fromisoformat(as_of) - timedelta(days=8)).isoformat()
    paid_since = (date.fromisoformat(as_of) - timedelta(days=3)).isoformat()
    base = ("SELECT a.customer_id, a.account_id, a.dpd FROM account a JOIN ds_consent c ON c.customer_id=a.customer_id "
            f"JOIN customer p ON p.customer_id=a.customer_id WHERE {CLEAN} AND a.legal_flag=0 AND ")
    rng = random.Random(seed)
    due = [dict(r) for r in db.query(base + "a.dpd=0 ORDER BY a.customer_id", (since, paid_since))]
    late = [dict(r) for r in db.query(base + "a.dpd BETWEEN 1 AND 60 ORDER BY a.customer_id", (since, paid_since))]
    pick = rng.sample(due, min(5, len(due))) + rng.sample(late, min(size - 5, len(late)))
    rng.shuffle(pick)
    now = time.time()
    for i, r in enumerate(pick):
        db.execute("INSERT INTO monitor_pool(customer_id, account_id, dpd, next_due, events) VALUES (?,?,?,?,0)",
                   (r["customer_id"], r["account_id"], r["dpd"], now + i * stagger_s))
    return [dict(r) for r in db.query("SELECT * FROM monitor_pool ORDER BY rowid")]


class LiveMonitor:
    def __init__(self, state, tick_s: float | None = None, every_min: float | None = None, window: str | None = None):
        self.state = state
        self.tick_s = tick_s if tick_s is not None else float(os.environ.get("MT02_MONITOR_TICK_S", 3))
        self.every_s = 60 * (every_min if every_min is not None else float(os.environ.get("MT02_MONITOR_EVERY_MIN", 30)))
        hard = state.sup.ctx.engine.hard_window
        self.window = parse_window(window or os.environ.get("MT02_MONITOR_WINDOW"), hard)
        self.paused = False
        self.processed = 0
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None
        self.last_error: str | None = None

    # ------------------------------------------------------------ control
    def start(self) -> None:
        if self._thread and self._thread.is_alive():
            return
        self._stop.clear()
        self._thread = threading.Thread(target=self._loop, daemon=True, name="live-monitor")
        self._thread.start()

    def stop(self) -> None:
        self._stop.set()

    def _loop(self) -> None:
        while not self._stop.wait(self.tick_s):
            try:
                self.tick()
            except Exception as e:  # noqa: BLE001 - the worker must never die
                self.last_error = repr(e)

    # ------------------------------------------------------------ one pass
    def in_window(self, now: datetime) -> bool:
        m = now.hour * 60 + now.minute
        return self.window[0] <= m < self.window[1]

    def tick(self, now: datetime | None = None) -> dict:
        """Append what has fallen due, then run every event whose time has arrived. Returns what it did."""
        now = now or datetime.now()
        done = added = 0
        if not self.paused and self.in_window(now):
            added = self._append_due(now)
            iso = now.isoformat(timespec="seconds")
            sup = self.state.sup
            for _ in range(200):
                if sup.process_next(until=iso) is None:
                    break
                done += 1
            self.processed += done
        return {"added": added, "processed": done, "state": self.status(now)["state"]}

    def _append_due(self, now: datetime) -> int:
        db, sup, ts = self.state.sup.ctx.db, self.state.sup, now.timestamp()
        n = 0
        for r in db.query("SELECT * FROM monitor_pool WHERE next_due <= ? ORDER BY next_due", (ts,)):
            busy = db.one("SELECT 1 FROM event_queue WHERE customer_id=? AND status IN ('PENDING','IN_PROGRESS')",
                          (r["customer_id"],))
            if busy:
                continue
            etype = "DUE_SOON" if r["dpd"] == 0 else "OVERDUE"
            eid = f"live-{int(ts * 1000)}-{r['customer_id']}"
            if sup.publish({"id": eid, "type": etype, "account_id": r["account_id"], "time": now.isoformat(timespec="seconds")}):
                n += 1
            db.execute("UPDATE monitor_pool SET next_due=?, events=events+1 WHERE customer_id=?", (ts + self.every_s, r["customer_id"]))
        return n

    # ------------------------------------------------------------ what the UI shows
    def status(self, now: datetime | None = None) -> dict:
        now = now or datetime.now()
        db = self.state.reader
        pool = db.one("SELECT COUNT(*) n, MIN(next_due) nxt FROM monitor_pool")
        handled = db.one("SELECT COUNT(DISTINCT customer_id) n FROM event_queue WHERE status='DONE' AND outcome != 'REJECTED' "
                         "AND customer_id IN (SELECT customer_id FROM monitor_pool)")["n"]
        waiting = db.one("SELECT COUNT(*) n FROM event_queue WHERE status='PENDING'")["n"]
        inside = self.in_window(now)
        state = "paused" if self.paused else ("monitoring" if inside else "outside_window")
        opens = None
        if not inside:
            day = now if now.hour * 60 + now.minute < self.window[0] else now + timedelta(days=1)
            opens = day.replace(hour=self.window[0] // 60, minute=self.window[0] % 60, second=0, microsecond=0).isoformat(timespec="minutes")
        label = {"monitoring": "Monitoring live", "paused": "Monitoring paused",
                 "outside_window": f"Outside contact hours. Resumes {opens[11:16]}" if opens else "Outside contact hours"}[state]
        return {"state": state, "label": label, "window": f"{hhmm(self.window[0])}–{hhmm(self.window[1])}",
                "now": now.isoformat(timespec="seconds"), "pool_size": pool["n"], "pool_handled": handled, "waiting": waiting,
                "processed": self.processed, "next_event_at": datetime.fromtimestamp(pool["nxt"]).isoformat(timespec="seconds") if pool["nxt"] else None,
                "opens_at": opens, "error": self.last_error}


def watched(db, now: datetime | None = None) -> list[dict]:
    """The pool, one row per watched customer: the account it is watched on, who owns the customer now, the last
    contact, the latest finished run and when the next event falls due. Read-only."""
    now = now or datetime.now()
    rows = []
    for r in db.query(
            "SELECT m.customer_id, m.account_id, m.next_due, m.events, a.dpd, a.product, p.name_masked, "
            "s.owner, s.lease_owner, s.lease_until, s.status "
            "FROM monitor_pool m LEFT JOIN account a ON a.account_id = m.account_id "
            "LEFT JOIN customer p ON p.customer_id = m.customer_id "
            "LEFT JOIN customer_state s ON s.customer_id = m.customer_id ORDER BY m.next_due"):
        d = dict(r)
        last = db.one("SELECT MAX(at) t FROM contact_log WHERE customer_id=? AND status IN ('SENT','ATTEMPTING')",
                      (d["customer_id"],))
        run = db.one("SELECT outcome, channel, finished_wall, fault FROM journey_run WHERE customer_id=? "
                     "ORDER BY finished_wall DESC LIMIT 1", (d["customer_id"],))
        lease_live = d["lease_owner"] and d["lease_until"] and d["lease_until"] > now.isoformat()
        d["owner"] = d["owner"] or (d["lease_owner"] if lease_live else None)
        d["last_contact"] = last["t"] if last else None
        d["last_outcome"] = run["outcome"] if run else None
        d["last_channel"] = run["channel"] if run else None
        d["last_fault"] = run["fault"] if run else None
        d["last_run_at"] = datetime.fromtimestamp(run["finished_wall"]).isoformat(timespec="seconds") if run else None
        d["next_due_at"] = datetime.fromtimestamp(d["next_due"]).isoformat(timespec="seconds") if d["next_due"] else None
        for k in ("next_due", "lease_owner", "lease_until"):
            d.pop(k, None)
        rows.append(d)
    return rows
